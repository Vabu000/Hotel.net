CREATE TABLE IF NOT EXISTS clients (
    clientid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fullname varchar(200) NOT NULL,
    passportdata varchar(100) NOT NULL,
    phone varchar(40) NOT NULL,
    email varchar(254) NOT NULL UNIQUE,
    createdat timestamptz NOT NULL DEFAULT now(),
    updatedat timestamptz NULL,
    isdeleted boolean NOT NULL DEFAULT false,
    version integer NOT NULL DEFAULT 1 CHECK (version > 0)
);

CREATE TABLE IF NOT EXISTS rooms (
    roomid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roomnumber varchar(30) NOT NULL UNIQUE,
    capacity integer NOT NULL CHECK (capacity > 0),
    price numeric(12,2) NOT NULL CHECK (price >= 0),
    createdat timestamptz NOT NULL DEFAULT now(),
    updatedat timestamptz NULL,
    isdeleted boolean NOT NULL DEFAULT false,
    version integer NOT NULL DEFAULT 1 CHECK (version > 0)
);

CREATE TABLE IF NOT EXISTS reservations (
    reservationid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clientid integer NOT NULL REFERENCES clients(clientid) ON DELETE RESTRICT,
    roomid integer NOT NULL REFERENCES rooms(roomid) ON DELETE RESTRICT,
    room_rate_snapshot numeric(12,2) NULL CHECK (room_rate_snapshot IS NULL OR room_rate_snapshot >= 0),
    checkindate date NOT NULL,
    checkoutdate date NOT NULL,
    status integer NOT NULL DEFAULT 0 CHECK (status BETWEEN 0 AND 4),
    createdat timestamptz NOT NULL DEFAULT now(),
    updatedat timestamptz NULL,
    isdeleted boolean NOT NULL DEFAULT false,
    version integer NOT NULL DEFAULT 1 CHECK (version > 0),
    CONSTRAINT ck_reservations_date_range CHECK (checkoutdate > checkindate)
);

CREATE TABLE IF NOT EXISTS reservation_details (
    reservationid integer PRIMARY KEY
        REFERENCES reservations(reservationid) ON DELETE CASCADE,
    guest_name varchar(200) NOT NULL,
    special_requests varchar(1000) NULL,
    createdat timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reservation_status_history (
    historyid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservationid integer NOT NULL
        REFERENCES reservations(reservationid) ON DELETE CASCADE,
    oldstatus integer NOT NULL CHECK (oldstatus BETWEEN 0 AND 4),
    newstatus integer NOT NULL CHECK (newstatus BETWEEN 0 AND 4),
    changedat timestamptz NOT NULL DEFAULT now(),
    changedby varchar(100) NULL
);

CREATE TABLE IF NOT EXISTS payments (
    paymentid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservationid integer NOT NULL
        REFERENCES reservations(reservationid) ON DELETE RESTRICT,
    amount numeric(12,2) NOT NULL CHECK (amount > 0),
    paymentdate timestamptz NOT NULL DEFAULT now(),
    method varchar(40) NOT NULL,
    createdat timestamptz NOT NULL DEFAULT now(),
    version integer NOT NULL DEFAULT 1 CHECK (version > 0)
);

CREATE TABLE IF NOT EXISTS catalog_service_snapshots (
    snapshotid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    catalog_service_id integer NOT NULL,
    name varchar(100) NOT NULL,
    price numeric(12,2) NOT NULL CHECK (price >= 0),
    capturedat timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_catalog_service_snapshot UNIQUE (catalog_service_id, capturedat)
);

CREATE TABLE IF NOT EXISTS catalog_services (
    catalog_service_id integer PRIMARY KEY,
    name varchar(120) NOT NULL,
    price numeric(12,2) NOT NULL CHECK (price >= 0),
    updatedat timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reservation_services (
    reservationid integer NOT NULL
        REFERENCES reservations(reservationid) ON DELETE CASCADE,
    snapshotid integer NOT NULL
        REFERENCES catalog_service_snapshots(snapshotid) ON DELETE RESTRICT,
    quantity integer NOT NULL DEFAULT 1 CHECK (quantity > 0),
    PRIMARY KEY (reservationid, snapshotid)
);

CREATE INDEX IF NOT EXISTS ix_reservations_client_checkin
    ON reservations (clientid, checkindate DESC)
    WHERE isdeleted = false;
CREATE INDEX IF NOT EXISTS ix_reservations_room_dates
    ON reservations (roomid, checkindate, checkoutdate)
    WHERE isdeleted = false;
CREATE INDEX IF NOT EXISTS ix_reservations_status
    ON reservations (status, checkindate);
CREATE INDEX IF NOT EXISTS ix_payment_reservation_date
    ON payments (reservationid, paymentdate DESC);
CREATE INDEX IF NOT EXISTS ix_reservation_status_history
    ON reservation_status_history (reservationid, changedat DESC);
-- The booking-time rate is an immutable snapshot. Legacy records remain NULL
-- because their historical rates cannot be reconstructed reliably.
ALTER TABLE reservations
    ADD COLUMN IF NOT EXISTS room_rate_snapshot numeric(12,2)
    CHECK (room_rate_snapshot IS NULL OR room_rate_snapshot >= 0);
-- Add consistent audit metadata to every Reservation-context table.
DO $$
DECLARE
    table_name text;
BEGIN
    FOREACH table_name IN ARRAY ARRAY[
        'clients', 'rooms', 'reservations', 'reservation_details',
        'reservation_status_history', 'payments', 'catalog_service_snapshots', 'reservation_services'
    ] LOOP
        EXECUTE format('ALTER TABLE %I ADD COLUMN IF NOT EXISTS createdat timestamptz NOT NULL DEFAULT now()', table_name);
        EXECUTE format('ALTER TABLE %I ADD COLUMN IF NOT EXISTS createdby varchar(100) NULL', table_name);
        EXECUTE format('ALTER TABLE %I ADD COLUMN IF NOT EXISTS updatedat timestamptz NULL', table_name);
        EXECUTE format('ALTER TABLE %I ADD COLUMN IF NOT EXISTS updatedby varchar(100) NULL', table_name);
        EXECUTE format('ALTER TABLE %I ADD COLUMN IF NOT EXISTS isdeleted boolean NOT NULL DEFAULT false', table_name);
        EXECUTE format('ALTER TABLE %I ADD COLUMN IF NOT EXISTS version integer NOT NULL DEFAULT 1 CHECK (version > 0)', table_name);
    END LOOP;
END $$;

CREATE INDEX IF NOT EXISTS ix_clients_active_email ON clients (email) WHERE isdeleted = false;
CREATE INDEX IF NOT EXISTS ix_rooms_active_number ON rooms (roomnumber) WHERE isdeleted = false;
CREATE INDEX IF NOT EXISTS ix_catalog_services_name ON catalog_services (name);

CREATE TABLE IF NOT EXISTS processed_events (
    event_id uuid PRIMARY KEY,
    event_type varchar(150) NOT NULL,
    processed_at timestamptz NOT NULL DEFAULT now()
);
