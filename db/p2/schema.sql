-- Project 2: Hotel Catalog PostgreSQL Schema (1:1, 1:N, M:N with payload, constraints, indexes)

CREATE TABLE IF NOT EXISTS roomcategories (
    categoryid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(100) NOT NULL,
    description character varying(500) NOT NULL,
    baseprice numeric(18,2) NOT NULL CHECK (baseprice >= 0)
);

CREATE TABLE IF NOT EXISTS roomcategorydetails (
    categoryid integer PRIMARY KEY REFERENCES roomcategories(categoryid) ON DELETE CASCADE,
    maxoccupancy integer NOT NULL CHECK (maxoccupancy > 0),
    area double precision NOT NULL CHECK (area > 0),
    bedtype character varying(80) NOT NULL
);

CREATE TABLE IF NOT EXISTS services (
    serviceid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(120) NOT NULL,
    price numeric(18,2) NOT NULL CHECK (price >= 0)
);

CREATE TABLE IF NOT EXISTS roomservices (
    categoryid integer NOT NULL REFERENCES roomcategories(categoryid) ON DELETE CASCADE,
    serviceid integer NOT NULL REFERENCES services(serviceid) ON DELETE CASCADE,
    additionalprice numeric(18,2) NOT NULL DEFAULT 0 CHECK (additionalprice >= 0),
    PRIMARY KEY (categoryid, serviceid)
);

CREATE TABLE IF NOT EXISTS discountcategories (
    discountcategoryid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(100) NOT NULL,
    discountpercentage numeric(5,2) NOT NULL CHECK (discountpercentage >= 0 AND discountpercentage <= 100)
);

CREATE TABLE IF NOT EXISTS clientdiscounts (
    clientid integer NOT NULL, -- logical reference to Reservations context (no cross-DB FK)
    discountcategoryid integer NOT NULL REFERENCES discountcategories(discountcategoryid) ON DELETE CASCADE,
    PRIMARY KEY (clientid, discountcategoryid)
);

-- Indexes for specific catalog lookup and filtering queries
CREATE INDEX IF NOT EXISTS ix_roomcategories_name ON roomcategories (name);
CREATE INDEX IF NOT EXISTS ix_services_name ON services (name);
CREATE UNIQUE INDEX IF NOT EXISTS ix_discountcategories_name ON discountcategories (name);
CREATE INDEX IF NOT EXISTS ix_roomservices_serviceid ON roomservices (serviceid);
